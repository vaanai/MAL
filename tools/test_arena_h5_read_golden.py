class GoldenA1(unittest.TestCase):
    """Old outputs unchanged: every scenario's stdout, stderr, exit code and JSON equal the golden files written from the unmodified tools."""

    def check(self, outputs: dict[str, str]) -> None:
        if WRITE:
            GOLDEN.mkdir(parents=True, exist_ok=True)
            for name, text in outputs.items():
                (GOLDEN / name).write_text(text)
        for name, text in outputs.items():
            with self.subTest(name=name):
                self.assertEqual(text, (GOLDEN / name).read_text(), f"{name} differs from the pre-change golden output")

    def test_read_a1_outputs_are_unchanged(self):
        self.check(read_outputs())

    def test_legs_a1_outputs_are_unchanged(self):
        self.check(legs_outputs())

    def test_the_golden_files_are_the_ones_listed(self):
        names = sorted(p.name for p in GOLDEN.iterdir())
        self.assertEqual(names, sorted(["read_both.txt", "read_both.json", "read_n_too_small.txt", "read_nd_and_refused.txt", "read_nd_and_refused.json",
                                        "read_q50_without_books_file.txt", "legs_full.txt", "legs_full.json", "legs_no_shadow.txt", "legs_q50_without_books_file.txt"]))


if __name__ == "__main__":
    unittest.main()
