def _mask_provenance(x):
    if isinstance(x, dict):
        return {k: ({kk: "<sha256>" for kk in v} if k == "provenance" and isinstance(v, dict) else _mask_provenance(v)) for k, v in x.items()}
    if isinstance(x, list):
        return [_mask_provenance(v) for v in x]
    return x


def _run(main, argv):
    """rc, stdout, stderr; an argparse exit is its code (prog pinned so the usage line does not depend on how the tests are run)."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err), mock.patch("sys.argv", ["prog"]):
        try:
            rc = main(list(argv))
        except SystemExit as exc:
            rc = exc.code
    return rc, out.getvalue(), err.getvalue()


