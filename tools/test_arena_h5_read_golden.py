def read_outputs() -> dict[str, str]:
    """The a1 read scenarios: both books by default (V1 PASS, V2 FAIL) with every multiplicity flag and --json; one NOT_DECIDABLE book; refusals beside the counts; one book REFUSED."""
    out: dict[str, str] = {}
    k = _ReadKit()
    k.setUp()
    try:
        root = str(k.root)
        norm = lambda s: s.replace(root, "<ROOT>")  # noqa: E731
        b1 = k.make_book(TR.V1, refused=3)
        b2 = k.make_book(TR.V2, kind=lambda d, i: "flat")
        ri = max(b1["ri"], b2["ri"])
        js = k.root / "out" / "read.json"
        js.parent.mkdir()
        rc, o, e = _run(R.main, k.args(ri, extra=("--cells-total", "123", "--prior-read", "hv4-CON-L=FAIL", "--other-p", "hv4-F=0.3", "--other-p", "j3-a1=0.02", "--json", str(js))))
        out["read_both.txt"] = norm(f"rc {rc}\n--- stdout\n{o}\n--- stderr\n{e}")
        out["read_both.json"] = norm(json.dumps(_mask_provenance(json.loads(js.read_text())), indent=1, sort_keys=True))
        rc, o, e = _run(R.main, k.args(ri, n="1"))
        out["read_n_too_small.txt"] = norm(f"rc {rc}\n--- stdout\n{o}\n--- stderr\n{e}")
    finally:
        k.doCleanups()
    k = _ReadKit()
    k.setUp()
    try:
        root = str(k.root)
        norm = lambda s: s.replace(root, "<ROOT>")  # noqa: E731
        b = k.make_book(TR.V1, excluded={(0, i) for i in range(7)})
        js = k.root / "nd.json"
        rc, o, e = _run(R.main, k.args(b["ri"], extra=("--other-p", "x=0.5", "--json", str(js))))  # V2 has no record: REFUSED beside the V1 read
        out["read_nd_and_refused.txt"] = norm(f"rc {rc}\n--- stdout\n{o}\n--- stderr\n{e}")
        out["read_nd_and_refused.json"] = norm(json.dumps(_mask_provenance(json.loads(js.read_text())), indent=1, sort_keys=True))
        rc, o, e = _run(R.main, k.args(b["ri"], "h5v1q50-boostfloor-a1"))
        out["read_q50_without_books_file.txt"] = norm(f"rc {rc}\n--- stdout\n{o}\n--- stderr\n{e}")
    finally:
        k.doCleanups()
    return out


