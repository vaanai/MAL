def sets_from_code(start: datetime, end: datetime, root: str | None, cfg: str | None) -> tuple[dict[str, Any], dict[str, list[tuple[str, float]]]]:
    """(screen D, {set name: [(key, decision block time)]}). The causal engine run is dbc_fwd.replay's `causal` variant without the log."""
    W.replay_guard(start, end, root)
    L.enable_swap3_pricing()
    if cfg:
        L.load_config_thresholds(cfg)
    D = S.load_exploration(root, log=lambda *_: None, start=start, end=end)
    A, pid = D["a"], D["pid"]
    names = D["pool_names"]
    bounds = np.flatnonzero(np.diff(pid)) + 1
    starts = np.concatenate([[0], bounds])
    s_of = {int(pid[s]): int(s) for s in starts}
    att, _ref, _st = S.cell_attempts(S.CELLS[[c.name for c in S.CELLS].index("m10")], D)
    s0 = [(W.key_of(names[a["pid"]], int(A["slot"][s_of[a["pid"]] + a["i"]]), float(A["S1"][s_of[a["pid"]] + a["i"]])), float(a["bt"])) for a in att]
    first_ok = D["start_ts"] + S.WARMUP_HOURS * 3600
    live_ss: dict[int, float] = {}
    eng = W.Engine(first_ok, ss_live=lambda hk, m=live_ss: S.slot_s_for(m, hk), ss_screen=lambda hk: S.slot_s_for(D["slot_s"], hk), good_hours=set(D["good_hours"]),
                   screen_policy=True, log=None, meta={"bt_src": "tape_block_time"})
    W.stream_hours(eng, start, end, root, live_ss, None)
    c1 = [(x["key"], float(x["bt"])) for x in eng.decisions_live]
    c2 = [(x["key"], float(x["bt"])) for x in eng.entries_screen]
    k0, k2 = {k for k, _ in s0}, {k for k, _ in c2}
    x1 = [(k, b) for k, b in s0 if k not in k2]
    x2 = [(k, b) for k, b in c2 if k not in k0]
    return D, {"C1": c1, "S0": s0, "C2": c2, "X1": x1, "X2": x2}


def check_sets(sets: dict[str, list[tuple[str, float]]], eq: dict[str, Any]) -> dict[str, Any]:
    cv, sc = eq["variants"]["causal"], eq["screen"]
    want = {"C1": ("md5", cv["md5_decisions_live_policy"], cv["decisions_live_policy"]), "S0": ("md5", sc["md5_entries"], sc["entries"]),
            "C2": ("md5", cv["md5_entries_screen_policy"], cv["entries_screen_policy"]), "X1": ("count", None, cv["entries_screen_only"]),
            "X2": ("count", None, cv["entries_engine_only"])}
    out: dict[str, Any] = {}
    for nm, (kind, md5, n) in want.items():
        keys = [k for k, _ in sets[nm]]
        got = W.md5_keys(keys)
        ok = len(keys) == n and len(set(keys)) == len(keys) and (md5 is None or got == md5)
        out[nm] = {"n": len(keys), "md5": got, "expected_md5": md5, "expected_n": n, "ok": ok, "checked_by": kind}
    out["all_ok"] = all(v["ok"] for v in out.values() if isinstance(v, dict))
    return out


class Pricer:
    """Per-key resolve on the full screen D (AM1) with the AM2 refusal rules."""

    def __init__(self, D: dict[str, Any]) -> None:
        self.D = D
        self.Dn = {**D, "bad_row": np.zeros_like(D["bad_row"])}
        A, pid = D["a"], D["pid"]
        names = D["pool_names"]
        bounds = np.flatnonzero(np.diff(pid)) + 1
        starts = np.concatenate([[0], bounds])
        ends = np.concatenate([bounds, [len(pid)]])
        self.slices: dict[int, tuple[int, int]] = {}
        self.index: dict[str, tuple[int, int]] = {}
        self.dup: set[str] = set()
        for s, e in zip(starts, ends):
            p = int(pid[s])
            self.slices[p] = (int(s), int(e))
            for j in range(int(s), int(e)):
                k = W.key_of(names[p], int(A["slot"][j]), float(A["S1"][j]))
                if k in self.index:
                    self.dup.add(k)
                self.index[k] = (p, j - int(s))
        self._pc: dict[tuple[int, bool], S.Pool] = {}
        self.cell = W.CELL

    def pool(self, p: int, zeroed: bool) -> S.Pool:
        if (p, zeroed) not in self._pc:
            s, e = self.slices[p]
            self._pc[(p, zeroed)] = S.Pool(self.Dn if zeroed else self.D, slice(s, e), p)
        return self._pc[(p, zeroed)]

    def resolve_set(self, items: list[tuple[str, float]], lat_in: float) -> dict[str, Any]:
        att: list[dict[str, Any]] = []
        fixed: list[tuple[float, str, str]] = []  # (lamports, date, reason)
        cnt = {"attempts": 0, "bad_state_zeroed_priced": 0, "bad_state_still_refused_full_loss": 0, "completed_before_entry": 0, "no_state": 0, "block_edge_excluded": 0,
               "bad_hour_excluded": 0, "key_not_found_full_loss": 0, "key_duplicate": 0, "other_refusal": 0}
        for k, bt in items:
            date = S.day_of(bt)
            if k not in self.index:
                cnt["key_not_found_full_loss"] += 1
                fixed.append((FULL_LOSS, date, "key_not_found"))
                continue
            if k in self.dup:
                cnt["key_duplicate"] += 1
            p, i = self.index[k]
            comp = self.D["complete_slot"].get(p)
            a, ref = S.resolve(self.cell, self.pool(p, False), [i], self.D, comp, lat_in, L.LAT_S)
            if a:
                att += a
                cnt["attempts"] += 1
                continue
            why = next(r for r, v in ref.items() if v)
            if why == "bad_state":
                a2, ref2 = S.resolve(self.cell, self.pool(p, True), [i], self.Dn, comp, lat_in, L.LAT_S)
                if a2:
                    att += a2
                    cnt["bad_state_zeroed_priced"] += 1
                else:
                    cnt["bad_state_still_refused_full_loss"] += 1
                    fixed.append((FULL_LOSS, date, "bad_state_still_refused"))
            elif why in ("completed_before_entry", "no_state"):
                cnt[why] += 1
                fixed.append((-float(SEND), date, why))
            elif why == "block_edge":
                cnt["block_edge_excluded"] += 1
            elif why == "bad_hour":
                cnt["bad_hour_excluded"] += 1
            else:
                cnt["other_refusal"] += 1
                fixed.append((FULL_LOSS, date, why))
        return {"att": att, "fixed": fixed, "counts": cnt}


def legs(att: list[dict[str, Any]], stake_sol: float = L.STAKE_DECIDING) -> dict[str, Any]:
    """dbc_screen.price_cell's lines (deciding defaults: rent 0, strand full loss), returning the per-attempt arrays."""
    g = lambda k: np.array([a[k] for a in att], float)  # noqa: E731
    mode = np.array([a["mode"] for a in att])
    ended = np.array([a["ended"] for a in att])
    pnl, filled, stranded = L.round_trip(stake_sol * 1e9, g("S_e"), g("L_e"), g("spot"), g("fee_in"), mode, g("S_x"), g("L_x"), g("fee_out"), quote_room=g("room"),
                                         rent=L.RENT_DECIDING, ended=ended, return_stranded=True)
    flat, press, c, p = F.fail_legs(pnl, filled, g("ssb"), g("nearby"), send=L.SEND_LAMPORTS)
    return {"flat": flat, "press": press, "nofail": pnl, "filled": filled, "stranded": stranded, "press_intercept": c, "mean_p": float(p[filled].mean()) if filled.any() else None,
            "dates": [a["date"] for a in att]}


def price(r: dict[str, Any]) -> dict[str, Any]:
    att, fixed = r["att"], r["fixed"]
    out: dict[str, Any] = {"counts": r["counts"], "n_priced": len(att) + len(fixed), "fixed_items": len(fixed)}
    if att:
        lg = legs(att)
        out.update({"fills": int(lg["filled"].sum()), "guard_unfilled": int((~lg["filled"]).sum()), "strands": int(lg["stranded"].sum()), "press_intercept": lg["press_intercept"],
                    "mean_p": lg["mean_p"]})
        if not fixed:  # the legs above are dbc_screen.price_cell's: check it
            pc = S.price_cell(att, L.STAKE_DECIDING)
            out["price_cell_check"] = all(pc[m]["n"] == len(att) and pc[m]["total"] == float((lg[m] / 1e9).sum()) for m in ("flat", "press"))
    else:
        lg = {"flat": np.array([]), "press": np.array([]), "nofail": np.array([]), "dates": []}
        out.update({"fills": 0, "guard_unfilled": 0, "strands": 0})
    fx = np.array([f[0] for f in fixed], float)
    dates = list(lg["dates"]) + [f[1] for f in fixed]
    for m in ("flat", "press", "nofail"):
        v = np.concatenate([np.asarray(lg[m], float), fx]) / 1e9
        out[m] = S.stat(v, dates) if len(v) else {"n": 0}
    return out


def kill_test(p19: dict[str, Any], p25: dict[str, Any]) -> dict[str, Any]:
    chk: dict[str, Any] = {}
    for m in ("flat", "press"):
        s, s25 = p19[m], p25[m]
        chk[m] = {"mean_gt_0": bool(s.get("n") and s["mean"] > 0), "ex_top3_gt_0": bool(s.get("ex_top3") is not None and s["ex_top3"] > 0),
                  "ci90_lo_trade_gt_0": bool(s.get("ci90_lo_trade") is not None and s["ci90_lo_trade"] > 0),
                  "entry_2p5s_mean_gt_0": bool(s25.get("n") and s25["mean"] > 0)}
    ok = all(all(v.values()) for v in chk.values())
    return {"verdict": "PASS" if ok else "FAIL", "checks": chk}


def run(out_dir: Path, start: datetime = START, end: datetime = END, root: str | None = None, cfg: str | None = CFG, eq_json: str = EQ_JSON) -> dict[str, Any]:
    t0 = time.time()
    eq = json.loads(Path(eq_json).read_text())
    D, sets = sets_from_code(start, end, root, cfg)
    chk = check_sets(sets, eq)
    here = Path(__file__).resolve().parent
    res: dict[str, Any] = {"schema": "dbc_fwd_sec3_v1", "ruling": RULING, "hours": [f"{start:%Y-%m-%dT%H}", f"{end:%Y-%m-%dT%H}"], "good_hours": len(D["good_hours"]),
                           "bad_hours": D["bad_hours"], "set_check": chk, "equivalence_json_sha256": hashlib.sha256(Path(eq_json).read_bytes()).hexdigest(),
                           "code_sha256": {f: W.sha256_file(here / f) for f in ("dbc_fwd_sec3.py", "dbc_fwd.py", "dbc_price.py", "dbc_screen.py", "arena_stack.py")},
                           "params": {"stake_sol": L.STAKE_DECIDING, "lat_s": L.LAT_S, "entry_2p5_s": 2.5, "send": SEND, "rent": L.RENT_DECIDING, "full_loss_lamports": FULL_LOSS,
                                      "guard": L.GUARD, "press_target_mean_p": F.PRESS_P_TARGET, "boot": [F.BOOT_DRAWS, F.BOOT_SEED, F.BOOT_PCT]}}
    if not chk["all_ok"]:
        res["verdict"] = "VOID"
        res["reason"] = "a regenerated set does not match the equivalence JSON (nothing priced)"
    else:
        pr = Pricer(D)
        res["key_index"] = {"rows": len(pr.index), "duplicate_keys": len(pr.dup)}
        res["sets"] = {}
        for nm in ("C1", "S0", "C2", "X1", "X2"):
            r19, r25 = pr.resolve_set(sets[nm], L.LAT_S), pr.resolve_set(sets[nm], 2.5)
            p19, p25 = price(r19), price(r25)
            nf = r19["counts"]["key_not_found_full_loss"] / max(len(sets[nm]), 1)
            res["sets"][nm] = {"n_decisions": len(sets[nm]), "primary_1p9s": p19, "entry_2p5s": {m: p25[m] for m in ("flat", "press")}, "entry_2p5s_counts": p25["counts"],
                               "not_found_share": nf, "not_decidable_not_found": nf > MAX_NOT_FOUND}
        c1 = res["sets"]["C1"]
        if c1["not_decidable_not_found"]:
            res["verdict"] = "NOT_DECIDABLE"
            res["reason"] = f"C1 keys not found {c1['not_found_share']:.4f} > {MAX_NOT_FOUND}"
        else:
            kt = kill_test(c1["primary_1p9s"], c1["entry_2p5s"])
            res["kill_test_C1"] = kt
            res["verdict"] = kt["verdict"]
    res["seconds"] = round(time.time() - t0, 1)
    res["taken_utc"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    res["note"] = ("IN-SAMPLE (m10 was selected on these hours; best of 23 screened cells; about 2.2 days of an ended venue state). Not evidence, not a gate pass. "
                   "No sentence may say m10 makes money.")
    return res


def write(out_dir: Path, res: dict[str, Any]) -> tuple[str, str]:
    txt = json.dumps(res, indent=1, default=float)
    (out_dir / OUT_JSON).write_text(txt)
    js = hashlib.sha256(txt.encode()).hexdigest()
    md = [f"# DBC m10 causal-only in-sample pricing (QP lookahead ruling section 3), {res['taken_utc']}", "", f"verdict (kill test on C1): **{res['verdict']}**", "",
          f"hours {res['hours']} (good {res['good_hours']}, bad {res['bad_hours']}); IN-SAMPLE, not evidence, not a gate pass.", ""]
    md += [f"- set {k}: n {v['n']} md5 {v['md5']} ok {v['ok']}" for k, v in res["set_check"].items() if isinstance(v, dict)]
    for nm, s in (res.get("sets") or {}).items():
        p = s["primary_1p9s"]
        md.append(f"## {nm} (decisions {s['n_decisions']}; priced {p['n_priced']}; fills {p['fills']}; guard-unfilled {p['guard_unfilled']}; strands {p['strands']})")
        md.append(f"- refusals/counts 1.9 s: {json.dumps(p['counts'])}")
        for m in ("flat", "press"):
            x = p[m]
            if x.get("n"):
                md.append(f"- {m}: n {x['n']} mean {x['mean']:.6f} total {x['total']:.4f} ex-top-3 {x['ex_top3']} ex-best-day {x['ex_best_day']:.4f} CI90 lo trade {x['ci90_lo_trade']} "
                          f"days {x['days_pos']}/{x['days']} per-day n {x['per_day_n']} per-day SOL {x['per_day']}; 2.5 s entry mean {s['entry_2p5s'][m].get('mean')}")
    if "kill_test_C1" in res:
        md.append(f"- kill test C1: {json.dumps(res['kill_test_C1'])}")
    md.append(f"- code sha256: {json.dumps(res['code_sha256'])}")
    md.append(f"- sha256 of {OUT_JSON}: {js}")
    (out_dir / OUT_MD).write_text("\n".join(md) + "\n")
    ms = hashlib.sha256((out_dir / OUT_MD).read_bytes()).hexdigest()
    return js, ms


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--copy-to", default="")
    ns = ap.parse_args(argv)
    out = Path(S.check_out_dir(ns.out))
    if out.exists() and any(out.iterdir()):
        print(f"REFUSED: output dir not empty: {out} (one run)", file=sys.stderr)
        return 3
    out.mkdir(parents=True, exist_ok=True)
    res = run(out)
    js, ms = write(out, res)
    print((out / OUT_MD).read_text())
    print(f"sha256 {OUT_JSON} {js}\nsha256 {OUT_MD} {ms}")
    if ns.copy_to:
        try:
            for f in (OUT_JSON, OUT_MD):
                shutil.copy2(out / f, Path(ns.copy_to) / f)
            print(f"copied to {ns.copy_to}")
        except OSError as e:
            print(f"COPY REFUSED ({type(e).__name__}): outputs stay in {out}", file=sys.stderr)
    return 0 if res["verdict"] in ("PASS", "FAIL") else 1


if __name__ == "__main__":
    sys.exit(main())
